// ---- formatted text --------------------------------------------------------------------------------------------

export type TextOptions<F extends CaptionFinding = CaptionFinding> = {
  prefs?: CaptionPrefs;
  visible?: (finding: F) => boolean;
  standardScript?: boolean;
};

/** The old text export's quote kind: an unknown source type reads as a verse (js/engine.js sourceTypeToCategorySlug). */
const textKind = (d: CaptionFinding) =>
  d.type || (d.sourceType === "HADITH" ? "hadith" : d.sourceType === "ADHKAR" ? "dhikr" : "ayah");

/** The lecture as one line of text with every quote in its brackets and its reference: Markdown makes the quote
 *  bold and the reference italic. Unlike the captions, the reference is the finding's own (no grouped ayah ranges),
 *  and of two findings starting on the same word the later one wins: both as in the old app. */
export function formattedText<F extends CaptionFinding>(
  words: CaptionWord[], detections: F[], format: "markdown" | "plain", options: TextOptions<F> = {},
): string {
  const prefs = options.prefs ?? {};
  const visible = options.visible ?? (() => true);
  const splitOn = prefs.splitCommentary !== false;
  let tokWord: number[] | null = null;
  const startMap = new Map<number, F>();
  (detections || []).forEach((d) => {
    if (typeof d.wordStartIdx === "number" && visible(d)) startMap.set(d.wordStartIdx, d);
  });
  const out: string[] = [];
  let i = 0;
  while (i < words.length) {
    const det = startMap.get(i);
    if (!det) {
      out.push(words[i].word);
      i++;
      continue;
    }
    const endW = Math.min(words.length - 1, Math.max(i, det.wordEndIdx));
    const brackets = bracketsFor(textKind(det), prefs);
    const useCanonical = Boolean((det.snappedToCanonical || options.standardScript) && det.canonicalText);
    const ref = det.displayRef || det.reference;
    const refBadge = ref ? ` [${ref}]` : "";
    if (splitOn && hasCommentaryGaps(det)) {
      const pieces = quotePieces(words, det, i, endW, useCanonical, (tokWord ??= tokenWordMap(words)), prefs);
      if (format === "markdown") {
        out.push(`${pieces.map((p) => (p.gap ? `[${p.text}]` : `**${brackets.open}${p.text}${brackets.close}**`)).join(" ")} *${refBadge}*`);
      } else {
        out.push(`${writePieces(pieces, brackets)}${refBadge}`);
      }
    } else {
      const body = useCanonical ? det.canonicalText! : words.slice(i, endW + 1).map((w) => w.word).join(" ");
      out.push(format === "markdown"
        ? `**${brackets.open}${body}${brackets.close}** *${refBadge}*`
        : `${brackets.open}${body}${brackets.close}${refBadge}`);
    }
    i = endW + 1;
  }
  return out.join(" ");
}

const escapeHtml = (s: string) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** A standalone right-to-left HTML page: the formatted text with each quote coloured by kind. */
export function toHtml<F extends CaptionFinding>(title: string, words: CaptionWord[], detections: F[], options: TextOptions<F> = {}): string {
  const caps = buildCaptions(words, detections, { prefs: options.prefs, visible: options.visible, standardScript: options.standardScript });
  const body = caps.map((c) => c.type === "normal"
    ? escapeHtml(c.displayText)
    : `<span class="citation-${c.type}">${escapeHtml(c.displayText)}</span>`).join(" ");
  const t = escapeHtml(title || "محاضرة منسقة — Wahy Studio");
  return `<!DOCTYPE html>
<html lang="ar" dir="rtl">
<head>
  <meta charset="UTF-8" />
  <title>${t}</title>
  <style>
    body { font-family: 'IBM Plex Sans Arabic', 'Noto Naskh Arabic', sans-serif; max-width: 900px; margin: 2rem auto; padding: 2rem; line-height: 2.1; }
    h1 { border-bottom: 1px solid #ccc; padding-bottom: 0.75rem; }
    .citation-ayah { color: #047857; font-family: 'Amiri', serif; font-size: 1.15rem; }
    .citation-hadith { color: #b45309; }
    .citation-dhikr { color: #6d28d9; }
  </style>
</head>
<body>
  <h1>${t}</h1>
  <div>${body}</div>
</body>
</html>
`;
}

