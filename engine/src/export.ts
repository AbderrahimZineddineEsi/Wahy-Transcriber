// Exports (ROADMAP phase 16): the old app's caption files (js/caption-builder.js exportCaptionsToSRT / VTT / ASS) and
// its formatted text (js/render.js buildFormattedPlainOrMarkdownLecture), moved here as pure functions so the server
// and the web app write the same files. Like captions.ts it imports nothing heavy (no engine, no corpus).
//
// The formats are the old code's, character for character (golden tests pin them). What is new:
//   - commentary gaps go outside the brackets, as in the captions (captions.ts; `prefs.splitCommentary: false` gives
//     the old text exactly);
//   - the verdict filter and "standard script" (F-038) are options, so an export shows what the screen shows;
//   - JSON and HTML are built from the lecture data instead of the page.
//
//   exportLecture({ format: "srt", words, findings, prefs, captionEdits, title })  →  { filename, mime, content }
import {
  applyCaptionEdits,
  bracketsFor,
  buildCaptions,
  hasCommentaryGaps,
  quotePieces,
  tokenWordMap,
  writePieces,
  type Caption,
  type CaptionEdit,
  type CaptionFinding,
  type CaptionPrefs,
  type CaptionWord,
} from "./captions.ts";

export type ExportFormat = "srt" | "vtt" | "ass" | "md" | "txt" | "json" | "html";
export const EXPORT_FORMATS: ExportFormat[] = ["srt", "vtt", "ass", "md", "txt", "json", "html"];

// ---- caption files ---------------------------------------------------------------------------------------------

/** "HH:MM:SS,mmm" (SRT) or "HH:MM:SS.mmm" (VTT). */
export function timestamp(sec: number, separator = "."): string {
  const s = Math.max(0, Number(sec) || 0);
  const ms = Math.round((s - Math.floor(s)) * 1000);
  const p = (n: number, w = 2) => String(n).padStart(w, "0");
  return `${p(Math.floor(s / 3600))}:${p(Math.floor((s % 3600) / 60))}:${p(Math.floor(s % 60))}${separator}${p(ms, 3)}`;
}

export function toSrt(captions: Caption[]): string {
  return (captions || []).map((c, idx) =>
    `${idx + 1}\n${timestamp(c.start, ",")} --> ${timestamp(c.end, ",")}\n${c.displayText || c.text || ""}\n`).join("\n");
}

const VTT_HEADER = [
  "WEBVTT",
  "",
  "STYLE",
  "::cue(c.ayah) { color: #6ee7b7; background-color: rgba(6, 78, 59, 0.82); font-family: 'Amiri', serif; }",
  "::cue(c.hadith) { color: #fcd34d; background-color: rgba(120, 53, 15, 0.82); }",
  "::cue(c.dhikr) { color: #a5b4fc; background-color: rgba(49, 46, 129, 0.82); }",
  "",
].join("\n");

/** WebVTT with a colour class per quote kind (<c.ayah>, <c.hadith>, <c.dhikr>). */
export function toVtt(captions: Caption[]): string {
  const blocks = (captions || []).map((c, idx) => {
    const body = c.displayText || c.text || "";
    const wrapped = c.type && c.type !== "normal" ? `<c.${c.type}>${body}</c>` : body;
    return `${idx + 1}\n${timestamp(c.start, ".")} --> ${timestamp(c.end, ".")}\n${wrapped}\n`;
  });
  return VTT_HEADER + "\n" + blocks.join("\n");
}

function assTime(sec: number): string {
  const s = Math.max(0, Number(sec) || 0);
  const cs = Math.floor((s - Math.floor(s)) * 100);
  const p = (n: number) => String(n).padStart(2, "0");
  return `${Math.floor(s / 3600)}:${p(Math.floor((s % 3600) / 60))}:${p(Math.floor(s % 60))}.${p(cs)}`;
}

