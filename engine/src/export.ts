export type ExportInput<F extends CaptionFinding = CaptionFinding> = {
  format: ExportFormat;
  words: CaptionWord[];
  findings: F[];
  title?: string;
  prefs?: CaptionPrefs;
  /** finding ids to show as quotes (the verdict filter); absent = all */
  visibleIds?: (string | number)[] | null;
  standardScript?: boolean;
  /** the caption timing editor's edits (captions.ts applyCaptionEdits) */
  captionEdits?: CaptionEdit[];
  /** the moment written into the JSON export (ISO text) */
  exportedAt?: string;
};

export type ExportFile = { filename: string; mime: string; content: string };

/** The lecture's captions as the export writes them: built, then the timing editor's edits applied. */
export function lectureCaptions<F extends CaptionFinding>(input: Omit<ExportInput<F>, "format">): Caption[] {
  const ids = input.visibleIds ? new Set(input.visibleIds.map(String)) : null;
  const visible = ids ? (f: F) => ids.has(String(f.id)) : undefined;
  const caps = buildCaptions(input.words, input.findings, { prefs: input.prefs, visible, standardScript: input.standardScript });
  return applyCaptionEdits(caps, input.words, input.captionEdits ?? []);
}

export function exportLecture<F extends CaptionFinding>(input: ExportInput<F>): ExportFile {
  const ids = input.visibleIds ? new Set(input.visibleIds.map(String)) : null;
  const visible = ids ? (f: F) => ids.has(String(f.id)) : undefined;
  const text = { prefs: input.prefs, visible, standardScript: input.standardScript };
  const title = input.title || "";
  switch (input.format) {
    case "srt":
      return { filename: "wahy-captions.srt", mime: "application/x-subrip", content: toSrt(lectureCaptions(input)) };
    case "vtt":
      return { filename: "wahy-captions.vtt", mime: "text/vtt", content: toVtt(lectureCaptions(input)) };
    case "ass":
      return { filename: "wahy-captions.ass", mime: "text/x-ssa", content: toAss(lectureCaptions(input), title) };
    case "md":
      return {
        filename: "wahy-lecture.md", mime: "text/markdown",
        content: `# ${title || "محاضرة علمية — Wahy Studio"}\n\n${formattedText(input.words, input.findings, "markdown", text)}\n`,
      };
    case "txt":
      return { filename: "wahy-lecture.txt", mime: "text/plain", content: formattedText(input.words, input.findings, "plain", text) };
    case "html":
      return { filename: "wahy-lecture-formatted.html", mime: "text/html", content: toHtml(title, input.words, input.findings, text) };
    case "json":
      return {
        filename: "wahy-lecture-data.json", mime: "application/json",
        content: JSON.stringify({
          version: "3.0.0",
          title,
          exportedAt: input.exportedAt ?? new Date().toISOString(),
          full_text: input.words.map((w) => String(w.word).trim()).join(" "),
          words: input.words,
          findings: ids ? input.findings.filter((f) => ids.has(String(f.id))) : input.findings,
          captions: lectureCaptions(input),
        }, null, 2),
      };
    default:
      throw new Error(`unknown export format "${input.format}" (${EXPORT_FORMATS.join(", ")})`);
  }
}
