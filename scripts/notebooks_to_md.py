"""Write a Markdown copy of each notebook to notebooks/md/ so graphify can read it.

Graphify has no .ipynb support. Outputs are dropped, and notebooks whose cells are
identical to one already written are skipped. Re-run after adding a notebook:

    python scripts/notebooks_to_md.py
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTEBOOKS = ROOT / "notebooks"
OUT = NOTEBOOKS / "md"


def cells_of(path):
    notebook = json.loads(path.read_text(encoding="utf-8"))
    return [
        (cell["cell_type"], "".join(cell["source"]).strip())
        for cell in notebook["cells"]
        if cell["cell_type"] in ("markdown", "code") and "".join(cell["source"]).strip()
    ]


def to_markdown(path, cells):
    rel = path.relative_to(ROOT).as_posix()
    parts = [f"# Notebook: {rel}", "Generated by scripts/notebooks_to_md.py. Outputs are not included."]
    for kind, source in cells:
        parts.append(source if kind == "markdown" else f"```python\n{source}\n```")
    return "\n\n".join(parts) + "\n"


def main():
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*.md"):
        old.unlink()

    seen = {}
    # Sorted so the finished Kaggle copies win ties against the notebooks they came from.
    paths = sorted(NOTEBOOKS.rglob("*.ipynb"), key=lambda p: ("finished" not in p.parts, p.as_posix()))
    for path in paths:
        cells = cells_of(path)
        digest = hashlib.sha256(json.dumps(cells).encode()).hexdigest()
        if digest in seen:
            print(f"skip {path.relative_to(ROOT)} (same as {seen[digest].relative_to(ROOT)})")
            continue
        seen[digest] = path
        name = "__".join(path.relative_to(NOTEBOOKS).with_suffix("").parts) + ".md"
        (OUT / name).write_text(to_markdown(path, cells), encoding="utf-8")
    print(f"wrote {len(seen)} of {len(paths)} notebooks to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
